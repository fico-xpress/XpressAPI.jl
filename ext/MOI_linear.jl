# --------------- MathOptInterface.Objective ---------------

# Scalar objective
function MOI.supports(::Optimizer, ::MOI.ObjectiveFunction{F})::Bool where {
        F <: Union{MOI.VariableIndex, MOI.ScalarAffineFunction}
    }
    return true
end

# Drop the currently-set objective before a new one is installed, so setting an
# objective replaces rather than accumulates. `model.objectives` holds one entry
# per Xpress objective: index 0 for a scalar objective, or 0..N-1 for a
# VectorOfVariables multi-objective (one linear objective per variable).
#
# XPRSdelobj clears an objective's linear and quadratic coefficients, operating
# on the Xpress problem directly (so no stale columns from since-deleted
# variables to filter out). For the extra objectives of a former multi-objective
# it removes them outright, shifting higher indices down -- hence we delete from
# the top. Objective 0 cannot be removed: XPRSdelobj clears it in place and
# leaves OBJECTIVES == 1. It also does not reset the objective constant, so we
# clear XPRS_OBJECTIVE_RHS explicitly; that matters for the FEASIBILITY_SENSE
# path, which clears the objective with no subsequent set to overwrite it.
function _clear_objective!(model::Optimizer)
    # Replacing the objective invalidates the current solution's duals/reduced
    # costs (and optimality), so drop stale caches. Every full objective re-set
    # (affine, single-variable, vector, quadratic) and the FEASIBILITY_SENSE
    # switch route through here, so this covers them all.
    _invalidate_solution_caches!(model)
    isempty(model.objectives) && return
    for objidx in (length(model.objectives) - 1):-1:0
        XPRSdelobj(model.inner, objidx)
    end
    XPRSsetobjdblcontrol(model.inner, 0, XPRS_OBJECTIVE_RHS, 0.0)
    empty!(model.objectives)
    return
end

function _add_linear_objective(model::Optimizer, objidx::Int, func::MOI.ScalarAffineFunction)
    # Sum duplicate terms on the same variable before handing them to Xpress:
    # XPRSchgobjn overwrites (last wins) rather than accumulating, so an
    # un-canonicalized function with repeated columns would set the wrong
    # coefficient. Work on a canonical copy so the caller's function is left
    # untouched and the cached objective matches what Xpress holds.
    if !MOI.Utilities.is_canonical(func)
        func = MOI.Utilities.canonical(func)
    end
    if length(func.terms) > 0
        XPRSchgobjn(
            model.inner,
            objidx,
            length(func.terms),
            map(t -> _XPRS_variable_from_moi_index(model, t.variable).xprs_index, func.terms),
            map(t -> Precision(t.coefficient), func.terms)
        )
    end

    # Set objective's constant
    XPRSsetobjdblcontrol(model.inner, objidx, XPRS_OBJECTIVE_RHS, func.constant)
    push!(model.objectives, func)
    return
end

# Linear objective R^n -> R
function MOI.set(model::Optimizer, ::MOI.ObjectiveFunction{F}, set::F) where {
        F <: MOI.ScalarAffineFunction
    }
    # Replace any previously-set objective rather than accumulating.
    _clear_objective!(model)
    # Add as objective '0' -> single objective
    _add_linear_objective(model, 0, set)
    model.objective_type = MOI.ScalarAffineFunction{Precision}
    # Return dummy index
    return MOI.VariableIndex(-1)
end

# Single variable objective x -> 1.0 * x + 0.0
function MOI.set(model::Optimizer, ::MOI.ObjectiveFunction{F}, set::F) where {
        F <: MOI.VariableIndex
    }
    t::MOI.ScalarAffineTerm{Precision} = MOI.ScalarAffineTerm(1.0, set)
    f::MOI.ScalarAffineFunction{Precision} = MOI.ScalarAffineFunction([t], 0.0)
    result = MOI.set(model, MOI.ObjectiveFunction{MOI.ScalarAffineFunction{Precision}}(), f)
    # Override the affine type set by the delegation above
    model.objective_type = MOI.VariableIndex
    return result
end

# --------------- modify MathOptInterface.ObjectiveFunction (in place) ---------------
# Change the linear objective (coefficients or constant) without re-setting the
# whole function. The single scalar objective is Xpress objective 0 (see
# `_add_linear_objective`), so a coefficient change routes to XPRSchgobjn on
# objective 0 and a constant change to XPRSsetobjdblcontrol on XPRS_OBJECTIVE_RHS
# (the same calls the setter uses). The cached objective (`model.objectives[end]`,
# returned by get(ObjectiveFunction)) is refreshed with MOI.Utilities.modify_function
# so the getter stays consistent; that helper also handles adding a new term or
# deleting one when a coefficient becomes zero.
#
# These methods dispatch on ObjectiveFunction{<: ScalarAffineFunction}, but that
# static type is not enough on its own: writing to objective 0 and caching into
# `model.objectives[end]` is only correct for the single scalar objective. Under a
# vector (multi-)objective -- VectorOfVariables or VectorAffineFunction -- the
# setter pushes one objective per row, so `objectives[end]` is the last per-row
# objective (index N-1), not objective 0 -- modifying it here would silently
# corrupt the wrong objective. `MOI.supports` advertises vector objectives
# unconditionally, so we cannot rule out a caller building a ScalarAffineFunction
# attribute while a vector objective is active; `_assert_scalar_objective` guards
# against it explicitly (any AbstractVectorFunction objective_type), throwing
# ModifyObjectiveNotAllowed rather than dispatching to the vector code path.

function _assert_scalar_objective(model::Optimizer, change)
    if model.objective_type <: MOI.AbstractVectorFunction
        throw(MOI.ModifyObjectiveNotAllowed(change,
            "in-place scalar objective modification is not supported for a vector (multi-)objective"))
    end
    if isempty(model.objectives)
        throw(MOI.ModifyObjectiveNotAllowed(change,
            "in-place objective modification requires an objective to be set first"))
    end
    return
end

# The single-change form delegates to the batched form with a one-element vector.
function MOI.modify(model::Optimizer, attr::MOI.ObjectiveFunction{F}, change::MOI.ScalarCoefficientChange) where {
        F <: MOI.ScalarAffineFunction
    }
    return MOI.modify(model, attr, [change])
end

# Vector form: apply many objective coefficient changes in a single XPRSchgobjn.
# Model state (objective_type, objectives) is identical for every element, so
# the guard is checked once against the first change rather than N times.
function MOI.modify(model::Optimizer, ::MOI.ObjectiveFunction{F}, changes::AbstractVector{<:MOI.ScalarCoefficientChange}) where {
        F <: MOI.ScalarAffineFunction
    }
    # Any modification drops the solution caches; do it first so an early return
    # or a failing precondition below can never leave a stale cache in place.
    _invalidate_solution_caches!(model)
    isempty(changes) && return
    _assert_scalar_objective(model, first(changes))
    colind = map(c -> _XPRS_variable_from_moi_index(model, c.variable).xprs_index, changes)
    objcoef = map(c -> Precision(c.new_coefficient), changes)
    XPRSchgobjn(model.inner, 0, length(changes), colind, objcoef)
    for change in changes
        model.objectives[end] = MOI.Utilities.modify_function(model.objectives[end], change)
    end
    return
end

# Change the objective's constant term in place (see the section comment above for
# why the VectorOfVariables guard is needed even though F is ScalarAffineFunction).
function MOI.modify(model::Optimizer, ::MOI.ObjectiveFunction{F}, change::MOI.ScalarConstantChange) where {
        F <: MOI.ScalarAffineFunction
    }
    # Any modification drops the solution caches; do it first so a failing
    # precondition below can never leave a stale cache in place.
    _invalidate_solution_caches!(model)
    _assert_scalar_objective(model, change)
    XPRSsetobjdblcontrol(model.inner, 0, XPRS_OBJECTIVE_RHS, Precision(change.new_constant))
    model.objectives[end] = MOI.Utilities.modify_function(model.objectives[end], change)
    return
end



# --------------- MathOptInterface.Constraints --------------
# https://jump.dev/MathOptInterface.jl/stable/manual/constraints/#Linear-constraints

# Bound to the solver's own coefficient type `Precision`: MOI queries
# supports_constraint with a "bad" coefficient type (e.g. UInt8) and expects
# false, so an unparameterized `F <: MOI.ScalarAffineFunction` (which matches
# any coefficient type) is too permissive.
function MOI.supports_constraint(model::Optimizer, ::Type{F}, ::Type{S})::Bool where {
        F <: MOI.ScalarAffineFunction{Precision},
        S <: Union{MOI.GreaterThan{Precision}, MOI.LessThan{Precision}, MOI.EqualTo{Precision}}
    }
    return true
end

function nrows(model::Optimizer, func::Vector{<: MOI.ScalarAffineFunction}, set::Vector{S}) where {
    S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
}
    # Number of rows to add
    return length(func)
end

function ncoefs(model::Optimizer, func::Vector{<: MOI.ScalarAffineFunction}, set::Vector{S}) where {
    S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
}
    # Total number of non-zero coefficients across all rows
    return sum(map(f -> length(f.terms), func))
end

function rowtypes(model::Optimizer, func::Vector{<: MOI.ScalarAffineFunction}, set::Vector{S}) where {
    S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
}
    # Type of the new rows
    return map(f -> begin
            if S <: MOI.EqualTo
                return 'E'
            end

            if S <: MOI.GreaterThan
                return 'G'
            end

            if S <: MOI.LessThan
                return 'L'
            end
        end,
        func
    )
end

function rhs(model::Optimizer, func::Vector{<: MOI.ScalarAffineFunction}, set::Vector{S}) where {
    S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
}
    # Type{P} array of length `nrows` containing the right hand side elements.
    # `_xprs_set_value` maps each scalar set to its RHS value (defined alongside
    # the in-place ConstraintSet setter in MOI_common.jl).
    return map(s -> Precision(_xprs_set_value(s)), set)
end

function starts(model::Optimizer, func::Vector{<: MOI.ScalarAffineFunction}, set::Vector{S}) where {
    S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
}
    # Start indices for each row in the coefficient arrays
    start_index = 0
    return vcat(0, map(f -> start_index += length(f.terms), func))
end

function colinds(model::Optimizer, func::Vector{<: MOI.ScalarAffineFunction}, set::Vector{S}) where {
    S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
}
    # Column indices for the coefficients (0-indexed) (concatenated for each rows)
    return vcat(
        map(
            f -> begin
                # Get XPRS indices of f's terms
                return map(t -> _XPRS_variable_from_moi_index(model, t.variable).xprs_index, f.terms)
            end,
            func
        )... # Expand outer vector into varargs for vcat
    )
end

function rowcoeffs(model::Optimizer, func::Vector{<: MOI.ScalarAffineFunction}, set::Vector{S}) where {
    S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
}
    # Coefficient values corresponding to colind
    return vcat(
        map(
            f -> begin
                # Get coefs of f's terms
                return map(t -> Precision(t.coefficient), f.terms)
            end,
            func
        )... # Expand outer vector into varargs for vcat
    )
end

function MOI.add_constraints(model::Optimizer, func::Vector{F}, set::Vector{S})::Vector{MOI.ConstraintIndex{F,S}} where {
        F <: MOI.ScalarAffineFunction,
        S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
    }

    if length(func) != length(set)
        throw(MOI.NotAllowedError("Cannot add constraint with |func| != |set|"))
    end

    # Add function in canonical form
    for f in func
        if !MOI.Utilities.is_canonical(f)
            MOI.Utilities.canonicalize!(f)
        end
    end

    old_n = XPRSgetattrib(model.inner, "ROWS")
    indices = map(
        # Generate new MOI.ConstraintIndex{MOI.ScalarAffineFunction, ...}
        i -> begin
            # Generate MOI index by adding dummy constraint
            return _XPRS_register_new_constraint(model, old_n + (i-1), func[i], set[i])
        end,
        # Range
        1:length(func)
    )

    XPRSaddrows64(
        model.inner,
        nrows(model, func, set),
        ncoefs(model, func, set),
        rowtypes(model, func, set),
        rhs(model, func, set),
        nothing,
        starts(model, func, set),
        colinds(model, func, set),
        rowcoeffs(model, func, set)
    )
    return indices
end

function MOI.add_constraint(model::Optimizer, func::F, set::S)::MOI.ConstraintIndex{F,S} where {
        F <: MOI.ScalarAffineFunction,
        S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
    }
    return MOI.add_constraints(model, [func], [set])[1]
end

# --------------- modify MathOptInterface.ConstraintFunction (in place) ---------------
# Change a linear constraint's coefficients without rebuilding the row: a scalar
# change routes to XPRSchgcoef, a vector of changes to the batched XPRSchgmcoef
# (`xprs_index` is already 0-based here, so no offset). The cached constraint
# function (`Constraint.moi_fct_value`, returned by get(ConstraintFunction)) is
# refreshed with MOI.Utilities.modify_function, which also adds a new term or
# deletes one when the new coefficient is zero (matching XPRSchgcoef, where a
# zero coefficient removes the matrix element).

# The single-change form delegates to the batched form with one-element vectors.
function MOI.modify(model::Optimizer, ci::MOI.ConstraintIndex{F,S}, change::MOI.ScalarCoefficientChange) where {
        F <: MOI.ScalarAffineFunction,
        S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
    }
    return MOI.modify(model, [ci], [change])
end

function MOI.modify(model::Optimizer, cis::AbstractVector{<:MOI.ConstraintIndex{F,S}}, changes::AbstractVector{<:MOI.ScalarCoefficientChange}) where {
        F <: MOI.ScalarAffineFunction,
        S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
    }
    # Any modification drops the solution caches; do it first so a failing
    # precondition below can never leave a stale cache in place.
    _invalidate_solution_caches!(model)
    if length(cis) != length(changes)
        # MOI.NotAllowedError is abstract and cannot be constructed; a count
        # mismatch between the index and change vectors is a caller usage error,
        # so DimensionMismatch (the idiomatic Julia error for mismatched lengths)
        # is thrown instead.
        throw(DimensionMismatch("modify: |cis| ($(length(cis))) != |changes| ($(length(changes)))"))
    end
    constraints = map(ci -> _XPRS_constraint_from_moi_index(model, ci), cis)
    rowind = map(c -> c.xprs_index, constraints)
    colind = map(ch -> _XPRS_variable_from_moi_index(model, ch.variable).xprs_index, changes)
    rowcoef = map(ch -> Precision(ch.new_coefficient), changes)
    XPRSchgmcoef(model.inner, length(changes), rowind, colind, rowcoef)
    for (c, change) in zip(constraints, changes)
        c.moi_fct_value = MOI.Utilities.modify_function(c.moi_fct_value, change)
    end
    return
end

# ZeroOne / Integer carry no coefficient type; the bound-like sets carry `{T}`
# and are bounded to `Precision` so a "bad" coefficient type (e.g. EqualTo{UInt8})
# is correctly rejected (see test_model_supports_constraint_VariableIndex_EqualTo).
function MOI.supports_constraint(model::Optimizer, ::Type{F}, ::Type{S})::Bool where {
        F <: MOI.VariableIndex,
        S <: Union{MOI.ZeroOne, MOI.Integer,
                   MOI.GreaterThan{Precision}, MOI.LessThan{Precision}, MOI.EqualTo{Precision},
                   MOI.Interval{Precision}, MOI.Semicontinuous{Precision}, MOI.Semiinteger{Precision}}
    }
    return true
end

function MOI.add_constraints(model::Optimizer, func::Vector{F}, set::Vector{S})::Vector{MOI.ConstraintIndex{F,S}} where {
        F <: MOI.VariableIndex,
        S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo, MOI.Interval, MOI.ZeroOne, MOI.Integer, MOI.Semicontinuous, MOI.Semiinteger}
    }

    if length(func) != length(set)
        throw(MOI.NotAllowedError("Cannot add constraint with |func| != |set|"))
    end

    # Split interval bounds into upper and lower bound calls
    if S <: MOI.Interval
        return map(
            i -> begin
                lb = MOI.add_constraint(model, func[i], MOI.GreaterThan(set[i].lower))
                ub = MOI.add_constraint(model, func[i], MOI.LessThan(set[i].upper))
                return _XPRS_register_new_constraint_as_parent(model, func[i], set[i], [lb, ub])
            end,
            1:length(func)
        )
    end

    # Retrieve variables info from the MOI indices
    variables = _XPRS_variable_from_moi_index.(model, func)
    # Convert bounds (that might even be int or bool) into the solver's desired precision (see below ifs)
    bounds = map(x -> Precision(Inf), set)
    # Deduce bounds senses from MOI scalar set type
    senses = map(x -> 'U', set)
    # Columns types (default is continuous)
    coltypes = map(x -> 'C', set)
    change_bounds = change_type = false

    # Bound sets map onto a column bound: sense and value come from the same
    # helpers used by the in-place ConstraintSet setter (see MOI_common.jl).
    if S <: Union{MOI.EqualTo, MOI.GreaterThan, MOI.LessThan}
        change_bounds = true
        senses = map(_xprs_bound_sense, set)
        bounds = map(s -> Precision(_xprs_set_value(s)), set)
    end

    if S <: MOI.ZeroOne
        model.has_integer_variables = true
        change_type = true
        coltypes = map(x -> 'B', set)
    end

    if S <: MOI.Integer
        model.has_integer_variables = true
        change_type = true
        coltypes = map(x -> 'I', set)
    end

    if S <: MOI.Semicontinuous
        model.has_integer_variables = true
        change_type = true
        coltypes = map(x -> 'S', set)
    end

    if S <: MOI.Semiinteger
        model.has_integer_variables = true
        change_type = true
        coltypes = map(x -> 'R', set)
    end

    # Since we are just updating bounds of existing variables, no constraints is added to the model
    if change_bounds
        XPRSchgbounds(
            model.inner,
            length(func),
            # Indices for the variables in Xpress matrix
            map(v -> v.xprs_index, variables),
            senses,
            bounds
        )
    end

    # Also change variable type if needed
    if change_type
        cols = map(v -> v.xprs_index, variables)
        # Marking a column binary resets its bounds to [0, 1] in Xpress,
        # clobbering any tighter user bound already set on the variable (and
        # the caching layer always copies integrality *after* bounds, so this
        # would silently drop e.g. a `x <= 1/2` or `x >= 1` bound regardless of
        # the order the user added the constraints). Snapshot the bounds first
        # and, once the type is set, re-apply them intersected with [0, 1].
        saved_bounds = S <: MOI.ZeroOne ? map(
            col -> (XPRSgetlb(model.inner, XPRS_ALLOC, col, col)[1],
                    XPRSgetub(model.inner, XPRS_ALLOC, col, col)[1]),
            cols
        ) : nothing
        XPRSchgcoltype(
            model.inner,
            length(func),
            # Indices for the variables in Xpress matrix
            cols,
            coltypes
        )
        if saved_bounds !== nothing
            XPRSchgbounds(
                model.inner,
                2 * length(cols),
                repeat(cols, inner = 2),
                repeat(['L', 'U'], length(cols)),
                collect(Iterators.flatten(
                    (max(lb, Precision(0)), min(ub, Precision(1))) for (lb, ub) in saved_bounds
                ))
            )
        end

        # A Semicontinuous(l, u) / Semiinteger(l, u) variable takes values in
        # {0} u [l, u]. The 'S'/'R' coltype alone only tells Xpress the column
        # is semi-continuous; the interval still has to be supplied as the
        # column's upper bound (u) and its semi-continuous lower limit (l, via
        # XPRSchgglblimit). Without these the variable is treated as an ordinary
        # continuous [0, +inf) column and the wrong optimum comes back.
        if S <: Union{MOI.Semicontinuous, MOI.Semiinteger}
            XPRSchgbounds(
                model.inner,
                length(cols),
                cols,
                fill('U', length(cols)),
                map(s -> Precision(s.upper), set)
            )
            XPRSchgglblimit(
                model.inner,
                length(cols),
                cols,
                map(s -> Precision(s.lower), set)
            )
        end
    end
    return map(
        i -> begin
            index = _XPRS_register_new_constraint(model, -2, func[i], set[i])
            return index
        end,
        1:length(func)
    )
end


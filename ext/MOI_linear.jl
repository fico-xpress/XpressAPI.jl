# SOS1 and SOS2
# https://jump.dev/MathOptInterface.jl/stable/manual/constraints/#Discrete-and-logical-constraints
function MOI.add_constraints(model::Optimizer, func::Vector{F}, set::Vector{S})::Vector{MOI.ConstraintIndex{F,S}} where {
        F <: MOI.VectorOfVariables,
        S <: Union{MOI.SOS1, MOI.SOS2}
    }

    if length(func) != length(set)
        throw(MOI.NotAllowedError("Cannot add constraint with |func| != |set|"))
    end

    # Number of new sets
    nsets = length(func)

    # Number of new nonzeros in the added sets
    nelems = sum(f -> length(f.variables), func)

    # Character array of length nsets containing the set types: 1 indicates a SOS1; 2 indicates a SOS2
    settypes = Char[]
    if S <: MOI.SOS1
        settypes = map(s -> '1', set)
    end
    if S <: MOI.SOS2
        settypes = map(s -> '2', set)
    end

    # Start indices for each row in the coefficient arrays
    start_index = 0
    starts = vcat(0, map(f -> start_index += length(f.variables), func))

    # Column indices for the reference value (0-indexed) (concatenated for each rows)
    colinds = vcat(
        map(
            f -> begin
                # Get XPRS indices of f's terms
                return map(v -> _XPRS_variable_from_moi_index(model, v).xprs_index, f.variables)
            end,
            func
        )... # Expand outer vector into varagrs for vcat
    )

    # Reference values corresponding to colind
    refvals = vcat(
        map(
            s -> begin
                # Get coefs of f's terms
                return map(w -> Precision(w), s.weights)
            end,
            set
        )... # Expand outer vector into varagrs for vcat
    )

    # Xpress appends the new sets after the existing ones; capture the current
    # count so each new constraint can record its 0-based Xpress set index (used
    # by MOI.delete to target the right set and renumber survivors).
    first_set = XPRSgetintattrib(model.inner, XPRS_SETS)

    XPRSaddsets64(
        model.inner,
        nsets,
        nelems,
        settypes,
        starts,
        colinds,
        refvals
    )

    return map(
        i -> begin
            index = _XPRS_register_new_constraint(model, -2, func[i], set[i])
            c = _XPRS_constraint_from_moi_index(model, index)
            c.xprs_set_index = first_set + (i - 1)
            return index
        end,
        1:length(func)
    )
end

function MOI.add_constraint(model::Optimizer, func::F, set::S)::MOI.ConstraintIndex{F,S} where {
        F <: MOI.VectorOfVariables,
        S <: Union{MOI.SOS1, MOI.SOS2}
    }
    return MOI.add_constraints(model, [func], [set])[1]
end

# --------------- VectorAffineFunction-in-set (row-wise) --------------
# A `VectorAffineFunction` in `Nonnegatives` / `Nonpositives` / `Zeros` is just a
# stack of scalar affine rows sharing one sense. We store it exactly like the
# indicator and interval paths do: the vector constraint is a *parent* constraint
# (xprs_index = -2, not itself a matrix row) whose `subconstraints` are the real
# per-row Xpress rows added through the ScalarAffineFunction path. The generic
# getters for ConstraintPrimal / ConstraintDual / ConstraintFunction already walk
# `subconstraints`, so no dedicated getter is needed here.
#
# Row i is `a_i'x + b_i in S`; the scalar add path takes its RHS purely from the
# scalar set and ignores the function constant, so the row constant b_i is folded
# into the RHS: `a_i'x + b_i >= 0` becomes `a_i'x >= -b_i`, etc.
#   Nonnegatives -> GreaterThan(-b_i);  Nonpositives -> LessThan(-b_i);  Zeros -> EqualTo(-b_i)

_vaf_scalar_set(::Type{<: MOI.Nonnegatives}, rhs) = MOI.GreaterThan(rhs)
_vaf_scalar_set(::Type{<: MOI.Nonpositives}, rhs) = MOI.LessThan(rhs)
_vaf_scalar_set(::Type{<: MOI.Zeros},        rhs) = MOI.EqualTo(rhs)

# Bounded to `Precision`: a complex-coefficient VectorAffineFunction (e.g.
# {Complex{Float64}}) is not supported and must be rejected here rather than
# force-converted to Float64 later (which throws InexactError). See
# test_linear_complex_Zeros.
function MOI.supports_constraint(model::Optimizer, ::Type{F}, ::Type{S})::Bool where {
        F <: MOI.VectorAffineFunction{Precision},
        S <: Union{MOI.Nonnegatives, MOI.Nonpositives, MOI.Zeros}
    }
    return true
end

function MOI.add_constraint(model::Optimizer, func::F, set::S)::MOI.ConstraintIndex{F,S} where {
        F <: MOI.VectorAffineFunction,
        S <: Union{MOI.Nonnegatives, MOI.Nonpositives, MOI.Zeros}
    }
    # Split the vector function into its scalar affine rows.
    rows = collect(MOI.Utilities.eachscalar(func))
    # Each row's constant folds into the RHS (see section comment above).
    scalar_sets = map(r -> _vaf_scalar_set(S, Precision(-r.constant)), rows)
    subs = MOI.add_constraints(model, rows, scalar_sets)
    return _XPRS_register_new_constraint_as_parent(model, func, set, subs)
end

# --------------------------- Constraint delete ---------------------------
# Each single delete drops the Xpress object(s), unregisters the cache entry, and
# renumbers survivors in one pass (see the helpers in MOI_common.jl). A batched
# delete of a vector of indices is the generic fallback below: it deletes one at a
# time, and because each delete renumbers immediately, the sequence stays correct.

# Scalar affine row: drop the row, unregister, renumber survivors.
function MOI.delete(model::Optimizer, ci::MOI.ConstraintIndex{F,S}) where {
        F <: MOI.ScalarAffineFunction,
        S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
    }
    c = _XPRS_constraint_from_moi_index(model, ci)
    row = c.xprs_index
    XPRSdelrows(model.inner, 1, [row])
    _XPRS_unregister_constraint(model, ci)
    _XPRS_shift_indices_after_row_delete!(model, [row])
    return
end

# Variable bound (GreaterThan/LessThan/EqualTo on a VariableIndex): reset the
# affected column bound(s) to free. No row exists, so nothing is renumbered.
# If the column is still binary, freeing the bound to +/-Inf would push it
# outside [0, 1] and Xpress would silently reclassify 'B' as general integer
# 'I' (giving e.g. an unbounded `min x`). So a binary column instead recomputes
# its bounds from the surviving bound constraints clamped to [0, 1], mirroring
# the ZeroOne add path -- the same fix as the ZeroOne-type delete below.
function MOI.delete(model::Optimizer, ci::MOI.ConstraintIndex{F,S}) where {
        F <: MOI.VariableIndex,
        S <: Union{MOI.GreaterThan, MOI.LessThan, MOI.EqualTo}
    }
    c = _XPRS_constraint_from_moi_index(model, ci)
    moi_var = c.moi_fct_value
    col = _XPRS_variable_from_moi_index(model, moi_var).xprs_index
    _XPRS_unregister_constraint(model, ci)
    if _XPRS_variable_is_zeroone(model, moi_var)
        _XPRS_restore_variable_bounds_from_cache!(model, moi_var, col)
    else
        _XPRS_reset_variable_bound(model, col, S)
    end
    return
end

# Reset the column bound(s) matching a deleted VariableIndex bound constraint back
# to free (-Inf / +Inf). GreaterThan resets the lower bound, LessThan the upper,
# EqualTo both.
function _XPRS_reset_variable_bound(model::Optimizer, col::Int, ::Type{<: MOI.GreaterThan})
    XPRSchgbounds(model.inner, 1, [col], ['L'], [Precision(-Inf)])
    return
end
function _XPRS_reset_variable_bound(model::Optimizer, col::Int, ::Type{<: MOI.LessThan})
    XPRSchgbounds(model.inner, 1, [col], ['U'], [Precision(Inf)])
    return
end
function _XPRS_reset_variable_bound(model::Optimizer, col::Int, ::Type{<: MOI.EqualTo})
    XPRSchgbounds(model.inner, 2, [col, col], ['L', 'U'], [Precision(-Inf), Precision(Inf)])
    return
end

# Recompute a column's bounds from the surviving VariableIndex bound constraints
# on `moi_var` and push them to Xpress. `col` is the 0-based Xpress column. A
# variable with no explicit bound constraint is left free (-Inf, +Inf), matching
# MOI's default and what a copy_to rebuild would produce. Called after a ZeroOne
# type reset, whose 'B' type had clamped the Xpress bounds to [0, 1] regardless of
# any explicit bound the model actually carries.
function _XPRS_restore_variable_bounds_from_cache!(model::Optimizer, moi_var::MOI.VariableIndex, col::Int)
    lb = Precision(-Inf)
    ub = Precision(Inf)
    is_zeroone = false
    for inner in values(model.constraints)
        for constraints in values(inner)
            for c in values(constraints)
                (c.moi_fct_value isa MOI.VariableIndex) || continue
                (c.moi_fct_value == moi_var) || continue
                s = c.moi_set_value
                if s isa MOI.GreaterThan
                    lb = Precision(s.lower)
                elseif s isa MOI.LessThan
                    ub = Precision(s.upper)
                elseif s isa MOI.EqualTo
                    lb = Precision(s.value)
                    ub = Precision(s.value)
                elseif s isa MOI.Interval
                    lb = Precision(s.lower)
                    ub = Precision(s.upper)
                elseif s isa MOI.ZeroOne
                    is_zeroone = true
                end
            end
        end
    end
    # A surviving ZeroOne keeps the column binary ('B'), so its bounds must stay
    # within [0, 1]. Intersect the reconstructed bounds with that range (mirroring
    # the ZeroOne add path) -- otherwise freeing a bound to +/-Inf would push the
    # column outside [0, 1] and Xpress would silently reclassify 'B' as general
    # integer 'I'. When the ZeroOne is being deleted it has already been
    # unregistered before this runs, so the flag is false and no clamp applies.
    if is_zeroone
        lb = Precision(max(lb, Precision(0.0)))
        ub = Precision(min(ub, Precision(1.0)))
    end
    XPRSchgbounds(model.inner, 2, [col, col], ['L', 'U'], [lb, ub])
    return
end

# Does `moi_var` still carry a ZeroOne (binary) VariableIndex constraint? Used by
# the bound-delete path to decide whether a freed column bound must be re-clamped
# to [0, 1] rather than opened to +/-Inf.
function _XPRS_variable_is_zeroone(model::Optimizer, moi_var::MOI.VariableIndex)
    for inner in values(model.constraints)
        for constraints in values(inner)
            for c in values(constraints)
                (c.moi_fct_value isa MOI.VariableIndex) || continue
                (c.moi_fct_value == moi_var) || continue
                (c.moi_set_value isa MOI.ZeroOne) && return true
            end
        end
    end
    return false
end

# Variable type (ZeroOne/Integer/Semicontinuous/Semiinteger on a VariableIndex):
# reset the column type back to continuous. The Integer/Semicontinuous/Semiinteger
# add paths change only the Xpress column TYPE, so their delete mirrors that and
# leaves the stored bounds alone. ZeroOne is special: making the column 'B' forces
# the Xpress bounds to [0, 1], clobbering any explicit bound (e.g. a separately
# added Interval). So after resetting a ZeroOne to 'C' we must recompute the bounds
# from the surviving bound constraints -- otherwise the column stays pinned to
# [0, 1] after the integrality is gone. No row is renumbered.
function MOI.delete(model::Optimizer, ci::MOI.ConstraintIndex{F,S}) where {
        F <: MOI.VariableIndex,
        S <: Union{MOI.ZeroOne, MOI.Integer, MOI.Semicontinuous, MOI.Semiinteger}
    }
    c = _XPRS_constraint_from_moi_index(model, ci)
    moi_var = c.moi_fct_value
    col = _XPRS_variable_from_moi_index(model, moi_var).xprs_index
    XPRSchgcoltype(model.inner, 1, [col], ['C'])
    _XPRS_unregister_constraint(model, ci)
    if S <: MOI.ZeroOne
        _XPRS_restore_variable_bounds_from_cache!(model, moi_var, col)
    end
    return
end

# Interval on a VariableIndex: a parent constraint (xprs_index = -2) whose children
# are the GreaterThan (lower) and LessThan (upper) bound resets. Reset both column
# bounds to free, unregister the children, then the parent. No row is renumbered.
function MOI.delete(model::Optimizer, ci::MOI.ConstraintIndex{F,S}) where {
        F <: MOI.VariableIndex,
        S <: MOI.Interval
    }
    c = _XPRS_constraint_from_moi_index(model, ci)
    col = _XPRS_variable_from_moi_index(model, c.moi_fct_value).xprs_index
    XPRSchgbounds(model.inner, 2, [col, col], ['L', 'U'], [Precision(-Inf), Precision(Inf)])
    for subc in c.subconstraints
        _XPRS_unregister_constraint(model,
            MOI.ConstraintIndex{subc.moi_fct_type, subc.moi_set_type}(subc.moi_index))
    end
    _XPRS_unregister_constraint(model, ci)
    return
end

# VectorAffineFunction (Nonnegatives/Nonpositives/Zeros): a parent constraint whose
# children are the real scalar rows. Delete all child rows in one batched call,
# unregister the children and parent, then renumber survivors.
function MOI.delete(model::Optimizer, ci::MOI.ConstraintIndex{F,S}) where {
        F <: MOI.VectorAffineFunction,
        S <: Union{MOI.Nonnegatives, MOI.Nonpositives, MOI.Zeros}
    }
    c = _XPRS_constraint_from_moi_index(model, ci)
    rows = sort!([subc.xprs_index for subc in c.subconstraints])
    if !isempty(rows)
        XPRSdelrows(model.inner, length(rows), rows)
    end
    for subc in c.subconstraints
        _XPRS_unregister_constraint(model,
            MOI.ConstraintIndex{subc.moi_fct_type, subc.moi_set_type}(subc.moi_index))
    end
    _XPRS_unregister_constraint(model, ci)
    _XPRS_shift_indices_after_row_delete!(model, rows)
    return
end

# SOS1/SOS2 (VectorOfVariables): drop the Xpress set, unregister, renumber the
# surviving SOS set indices. No matrix row is involved.
function MOI.delete(model::Optimizer, ci::MOI.ConstraintIndex{F,S}) where {
        F <: MOI.VectorOfVariables,
        S <: Union{MOI.SOS1, MOI.SOS2}
    }
    c = _XPRS_constraint_from_moi_index(model, ci)
    set_index = c.xprs_set_index
    XPRSdelsets(model.inner, 1, [set_index])
    _XPRS_unregister_constraint(model, ci)
    _XPRS_shift_sos_indices_after_delete!(model, [set_index])
    return
end

# Generic batch fallback: delete one at a time. Each single delete renumbers
# survivors immediately, so a sequential loop stays correct.
function MOI.delete(model::Optimizer, indices::Vector{<: MOI.ConstraintIndex})
    for index in indices
        MOI.delete(model, index)
    end
    return
end

# In-place MultirowChange: change one variable's coefficient across several rows
# of a VectorAffineFunction constraint in a single batched XPRSchgmcoef. The rows
# are the parent's `subconstraints`; MultirowChange output rows are 1-based, so
# they index straight into that vector. `xprs_index` is already 0-based for the
# XPRSchgmcoef call. The parent's cached VectorAffineFunction and each touched
# subconstraint's cached ScalarAffineFunction are refreshed so the getters stay
# consistent (a zero coefficient removes the term, matching XPRSchgmcoef).
# If the same output row appears multiple times in `new_coefficients`, entries
# are applied in list order and the last value wins -- both in the XPRSchgmcoef
# call and in the refreshed cached functions, so the two stay consistent.
# `new_coefficients` is a Vector, so this order is deterministic.
function MOI.modify(model::Optimizer, ci::MOI.ConstraintIndex{F,S}, change::MOI.MultirowChange) where {
        F <: MOI.VectorAffineFunction,
        S <: Union{MOI.Nonnegatives, MOI.Nonpositives, MOI.Zeros}
    }
    # Any modification drops the solution caches; do it first so an early return
    # or a failing precondition below can never leave a stale cache in place.
    _invalidate_solution_caches!(model)
    isempty(change.new_coefficients) && return
    c = _XPRS_constraint_from_moi_index(model, ci)
    nrows = length(c.subconstraints)
    for (output_row, _) in change.new_coefficients
        if output_row < 1 || output_row > nrows
            throw(MOI.ModifyConstraintNotAllowed(ci, change,
                "MultirowChange output row $output_row is out of range 1:$nrows"))
        end
    end
    col = _XPRS_variable_from_moi_index(model, change.variable).xprs_index
    rowind = map(p -> c.subconstraints[p[1]].xprs_index, change.new_coefficients)
    colind = fill(col, length(change.new_coefficients))
    rowcoef = map(p -> Precision(p[2]), change.new_coefficients)
    XPRSchgmcoef(model.inner, length(change.new_coefficients), rowind, colind, rowcoef)
    # Keep the parent's cached VectorAffineFunction consistent.
    c.moi_fct_value = MOI.Utilities.modify_function(c.moi_fct_value, change)
    # Keep each touched row's cached ScalarAffineFunction consistent.
    for (output_row, coef) in change.new_coefficients
        subc = c.subconstraints[output_row]
        subc.moi_fct_value = MOI.Utilities.modify_function(
            subc.moi_fct_value, MOI.ScalarCoefficientChange(change.variable, coef))
    end
    return
end

# Vector Objective of variables: Min/Max [x1,...,xn]
function MOI.supports(::Optimizer, ::MOI.ObjectiveFunction{F})::Bool where {
        F <: MOI.VectorOfVariables
    }
    return true
end

function MOI.set(model::Optimizer, ::MOI.ObjectiveFunction{F}, set::F) where {
        F <: MOI.VectorOfVariables
    }
    # Replace any previously-set objective rather than accumulating.
    _clear_objective!(model)
    result = map(
        i -> begin
            # v -> 1v + 0
            t::MOI.ScalarAffineTerm{Precision} = MOI.ScalarAffineTerm(1.0, set.variables[i])
            f::MOI.ScalarAffineFunction{Precision} = MOI.ScalarAffineFunction([t], 0.0)
            _add_linear_objective(model, i-1, f)
            return MOI.VariableIndex(-1)
        end,
        1:length(set.variables)
    )
    model.objective_type = MOI.VectorOfVariables
    return result
end

# Vector affine objective: Min/Max [a1'x + b1, ..., an'x + bn]. Supported
# natively (one linear Xpress objective per row) rather than through MOI's
# VectorSlackBridge, so that variable deletion, coefficient modification and
# get(ObjectiveFunction) round-trip faithfully: the bridge stores any bare
# variable row (e.g. a row that is just `x[i]`) as a raw VariableIndex and never
# updates it when that variable is deleted, returning a stale function. Handling
# the objective natively lets the caching layer keep it in sync, exactly as for
# a VectorOfVariables objective. See TXP-9392.
function MOI.supports(::Optimizer, ::MOI.ObjectiveFunction{F})::Bool where {
        F <: MOI.VectorAffineFunction
    }
    return true
end

function MOI.set(model::Optimizer, ::MOI.ObjectiveFunction{F}, set::F) where {
        F <: MOI.VectorAffineFunction
    }
    # Replace any previously-set objective rather than accumulating.
    _clear_objective!(model)
    # Each scalar row becomes one Xpress objective (0-based index).
    rows = collect(MOI.Utilities.eachscalar(set))
    for i in 1:length(rows)
